package uniquindio.edu.co.proyectofinal.modelo;

/**
 * Roles que puede desempeñar un empleado del alojamiento.
 */
public enum RolEmpleado {

    /**
     * Atiende reservas, llegadas y salidas.
     */
    RECEPCIONISTA,

    /**
     * Administra el alojamiento.
     */
    ADMINISTRADOR,

    /**
     * Realiza la preparación de los apartamentos.
     */
    PERSONAL_PREPARACION
}
